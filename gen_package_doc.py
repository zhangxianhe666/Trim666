# -*- coding: utf-8 -*-
"""把「给 AI 的模板」生成到 package_docs，随分发包一起发给最终用户。
内容 = 一页说明 + 模板正文（正文直接从 manual_patch 读取，避免两份漂移）。
"""
import os

ROOT = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(ROOT, 'manual_patch', '最终版-补工具与技能-模板.txt')
DST = os.path.join(ROOT, 'package_docs', '3-扩展工具与提示词.txt')

HEADER = """\
================================================================
  3 · 任务超出 7 个工具时：让 AI 帮你补「工具 + 提示词」
================================================================

【什么时候用】
  内置 7 个工具（shell / 读文件 / 找文件 / 写文件 / 改文件 / 搜索 / 抓网页）
  覆盖不了的任务，比如：Excel 汇总、Word 报告、PDF 提取、批量改图片；
  或者客户端装了技能（PPT / docx），想让 trim 用上。

【为什么不能随便加工具】
  模型靠名字调工具（<invoke name="Write">…</invoke>），网关把名字转给客户端后，
  客户端会拿自己的工具表严格校验。名字或参数对不上，整轮被拒，
  现象是「模型说做完了，但文件没出现」。所以客户端没有的工具，造出来也没用。

  这决定了补什么只有四种情况：
    A 客户端本来就有、只是清单没列     -> 补一条工具 JSON
    B 客户端根本没有（Excel/Word…）    -> 不造工具，shell 拼命令，写进提示词
    C 工具够用，只是缺做法             -> 只补提示词规则
    K 客户端装了技能                   -> 写一条「技能入口规则」，顶掉旧的土办法
  多数任务是 B + C 混合。

【三步】
  1) 复制下面的模板到任意会写代码的 AI（网页版 DeepSeek / 新开一个对话都行）。
     要填的只有五处，都标了「（提示：…）」，提示行不用删：
       客户端        -> 写 WorkBuddy 或 DSH
       上限          -> 抄「提示词」页底部「system 最大字符数」那个数字
       工具 JSON     -> 复制 trim「工具 (JSON)」页整段
       提示词        -> 复制 trim「提示词」页整段
       任务 / 期望产物 -> 自己一句话写清
     装了技能的，再多填一行技能目录，别的不填——技能怎么用由 AI 自己判断。
  2) 它只回两段：工具 JSON + 提示词规则，末尾带两行凭证：
       「需删除：…」    它指出哪几条旧规则该删（没有就写「无」）
       「字数：新增 N…」新增了多少字；模板把新增量硬顶在 600 字，超了会自己砍条数
  3) 贴回 trim：
       「工具 (JSON)」页  -> 整段替换成它给的完整数组 -> 点「校验并格式化」
       「提示词」页        -> 末尾(Ctrl+End) -> 换行 -> 粘贴它给的 9) 10) 那几行
                             （编号接着你现有最后一条往下排，不用自己改）
                             它写了「需删除」的，先删掉那几条再粘
       点「保存配置」-> 看到「网关热重载」即生效

【贴之前扫一眼这五点】
  - 输出里出现你没见过的工具名（比如 Excel）-> 客户端没有，让它「按 B 类重做」。
  - 它把整份提示词重写了一遍 -> 只要「二、提示词」那段，别整份覆盖，
    否则你原有的文档处理规则会被弄丢。
  - 规则里出现了这次任务的具体文件名（比如 D:\报告.docx）-> 让它改成
    「从我当次说的话里取」，否则下次换个文件就不管用了。
  - 技能规则和旧规则并存（比如同时有 COM 生成 pptx 和技能入口）->
    模型会在两条路之间反复横跳，必须二选一。
  - 粘完发现提示词末尾被截掉 -> 「提示词」页底部把 system 最大字符数改大
    （0 = 不截断），再点保存配置。

----------------------------------------------------------------
  下面是模板正文（整段复制给 AI）
----------------------------------------------------------------

"""


def main():
    with open(SRC, encoding='utf-8') as f:
        body = f.read()
    text = HEADER + body.replace('\n', '\r\n')
    os.makedirs(os.path.dirname(DST), exist_ok=True)
    with open(DST, 'w', encoding='utf-8', newline='\r\n') as f:
        f.write(text)
    print('written:', DST, os.path.getsize(DST), 'bytes')
    print('模板正文行数:', body.count('\n') + 1, '字符数:', len(body))


if __name__ == '__main__':
    main()
